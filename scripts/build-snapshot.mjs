// Transpiles src/engine/snapshot.browser.ts into a plain-JS string module so it
// can be injected with page.evaluate without bundler helpers (__name etc.).
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const r = await build({
  entryPoints: ["src/engine/snapshot.browser.ts"],
  bundle: false,
  write: false,
  format: "esm",
  target: "es2022",
  keepNames: false,
  minify: false,
});
let js = r.outputFiles[0].text;
js = js.replace(/^export function captureSnapshot/m, "function captureSnapshot").replace(/export\s*\{[\s\S]*?\};?\s*$/m, "");
if (/__name|__publicField/.test(js)) throw new Error("bundler helpers leaked into snapshot script");
const out = `// GENERATED by scripts/build-snapshot.mjs from snapshot.browser.ts — do not edit.
export const SNAPSHOT_SCRIPT = ${JSON.stringify(`(() => {\n${js}\nreturn captureSnapshot();\n})()`)};
`;
await writeFile("src/engine/snapshot.generated.ts", out);
console.log(`snapshot script: ${js.length} chars`);
